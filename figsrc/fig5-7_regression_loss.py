"""
regression_loss.py
アクセルの値 x と、実際の速さ y（m/s）のデータに、直線 y = w x + b を合わせる。
いくつかの直線について、合い具合（損失）を計算して比べる。
"""

import numpy as np

# 作ったデータ：アクセルの値と、そのとき測った速さ（m/s）
x = np.array([0.10, 0.15, 0.20, 0.25, 0.30, 0.35, 0.40, 0.45, 0.50, 0.55, 0.60])
y = np.array([0.12, 0.29, 0.41, 0.46, 0.59, 0.70, 0.86, 0.96, 1.11, 1.13, 1.38])


def predict(w, b):
    """直線 y = w x + b で、それぞれの x の速さを予想する"""
    return w * x + b


def loss(w, b):
    """平均二乗誤差：予想と実際の差を2乗して、平均する"""
    error = y - predict(w, b)
    return np.mean(error ** 2)


for w, b in [(2.0, 0.0), (3.0, -0.3), (2.4, -0.1)]:
    print(f"w = {w}, b = {b:5.2f}  →  損失 {loss(w, b):.5f}")
